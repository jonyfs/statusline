#!/usr/bin/env node
/**
 * Regenerates src/data/wide.js, the table `displayWidth` reads to decide
 * which characters take two columns.
 *
 *   node scripts/generate-width-table.js
 *
 * A character is wide when Unicode gives it East Asian Width `W` or `F`, or
 * `Emoji_Presentation=Yes`. The two inputs are committed under
 * scripts/unicode-16.0.0/, each reduced to the lines this reads, so the
 * generator touches no network and the result is the same on every machine.
 * To move to a newer Unicode, replace the two extracts and run this again.
 */

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dir = path.join(here, "unicode-16.0.0");

export const SOURCES = {
  eastAsianWidth: path.join(dir, "EastAsianWidth.extract.txt"),
  emojiData: path.join(dir, "emoji-data.extract.txt"),
};

const OUTPUT = path.join(here, "..", "src", "data", "wide.js");

function versionOf(text, label) {
  const m = /\b(\d+\.\d+\.\d+)\b/.exec(text.split("\n", 1)[0]);
  if (!m) throw new Error(`${label}: the first line names no Unicode version`);
  return m[1];
}

/** Code point ranges from lines such as `1F7E0..1F7EB ; W # ...`. */
function readRanges(text, wanted) {
  const ranges = [];
  for (const raw of text.split("\n")) {
    const line = raw.replace(/#.*$/, "").trim();
    if (!line) continue;
    const [cps, prop] = line.split(";").map((s) => s.trim());
    if (!wanted.includes(prop)) continue;
    const [lo, hi = lo] = cps.split("..");
    ranges.push([parseInt(lo, 16), parseInt(hi, 16)]);
  }
  return ranges;
}

/** Sorts and merges ranges that overlap or touch. */
function merge(ranges) {
  const sorted = [...ranges].sort((a, b) => a[0] - b[0]);
  const out = [];
  for (const [lo, hi] of sorted) {
    const last = out[out.length - 1];
    if (last && lo <= last[1] + 1) last[1] = Math.max(last[1], hi);
    else out.push([lo, hi]);
  }
  return out;
}

export function buildTable(eastAsianWidthText, emojiDataText) {
  const version = versionOf(eastAsianWidthText, "EastAsianWidth");
  const emojiVersion = versionOf(emojiDataText, "emoji-data");
  if (version !== emojiVersion) {
    throw new Error(`the sources disagree on the Unicode version: ${version} and ${emojiVersion}`);
  }
  const ranges = merge([
    ...readRanges(eastAsianWidthText, ["W", "F"]),
    ...readRanges(emojiDataText, ["Emoji_Presentation"]),
  ]);
  return { version, ranges };
}

export function renderModule({ version, ranges }) {
  const hex = (n) => "0x" + n.toString(16);
  const rows = ranges.map(([lo, hi]) => `  [${hex(lo)}, ${hex(hi)}],`).join("\n");
  return [
    "// Generated by scripts/generate-width-table.js. Do not edit by hand.",
    "//",
    "// The code points drawn two columns wide: East Asian Width W or F, plus",
    "// Emoji_Presentation=Yes. Sorted, merged, inclusive ranges.",
    `export const UNICODE_VERSION = ${JSON.stringify(version)};`,
    "",
    "export const WIDE = [",
    rows,
    "];",
    "",
  ].join("\n");
}

function main() {
  const table = buildTable(
    readFileSync(SOURCES.eastAsianWidth, "utf8"),
    readFileSync(SOURCES.emojiData, "utf8")
  );
  writeFileSync(OUTPUT, renderModule(table));
  console.log(`wrote ${path.relative(process.cwd(), OUTPUT)}: ${table.ranges.length} ranges, Unicode ${table.version}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
